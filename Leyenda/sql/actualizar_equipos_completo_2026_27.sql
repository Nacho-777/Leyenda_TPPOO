-- Este script SOLO crea/actualiza la tabla equipos; no elimina ni modifica jugadores.

CREATE TABLE IF NOT EXISTS equipos (
    id INT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(100) DEFAULT NULL,
    pais VARCHAR(50) DEFAULT NULL,
    tier VARCHAR(50) DEFAULT NULL,
    competicion VARCHAR(100) DEFAULT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

ALTER TABLE equipos MODIFY nombre VARCHAR(100) DEFAULT NULL;

-- Compatibilidad con instalaciones anteriores que todavia no tenian la columna competicion.
SET @existe_competicion = (
    SELECT COUNT(*) FROM information_schema.COLUMNS
    WHERE TABLE_SCHEMA = DATABASE()
      AND TABLE_NAME = 'equipos'
      AND COLUMN_NAME = 'competicion'
);
SET @agregar_competicion = IF(
    @existe_competicion = 0,
    'ALTER TABLE equipos ADD COLUMN competicion VARCHAR(100) DEFAULT NULL',
    'SELECT ''La columna competicion ya existe'' AS mensaje'
);
PREPARE stmt_competicion FROM @agregar_competicion;
EXECUTE stmt_competicion;
DEALLOCATE PREPARE stmt_competicion;

